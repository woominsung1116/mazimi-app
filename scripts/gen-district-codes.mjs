#!/usr/bin/env node
// Emits the client 시·군·구 list from crates/worker/src/district_codes.rs
// (DISTRICTS + LEGACY, the official 법정동 file) for the web and mobile apps.
//
// The 2026 file numbers 광주광역시 and 전라남도 together as 12xxx, which
// mazimi_core::structural::district_region does not read; a profile city_code
// of 12210 counts as absent. Those districts are emitted under their retired
// 29xxx (광주) / 46xxx (전남) code instead, which the server matches through
// each programme's aliases. 강원 51xxx and 전북 52xxx are read by the core
// directly. `worker` test `regions::tests::client_district_lists_match_core`
// checks every emitted code against the core.
//
// Usage: node scripts/gen-district-codes.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(join(root, "crates/worker/src/district_codes.rs"), "utf8");

const table = (name) => {
  const start = source.indexOf(`pub const ${name}:`);
  if (start < 0) throw new Error(`${name} not found`);
  const body = source.slice(start, source.indexOf("];", start));
  return [...body.matchAll(/\(([^()]*)\)/g)]
    .map((m) => [...m[1].matchAll(/"([^"]*)"/g)].map((s) => s[1]))
    .filter((row) => row.length >= 2);
};
const districts = table("DISTRICTS");
const legacy = new Map(table("LEGACY").map(([old, current]) => [current, old]));
// Reviewed successors of retired codes (scripts/district-successors.tsv).
const currentCodes = new Set(districts.map(([code]) => code));
const successors = readFileSync(join(root, "scripts/district-successors.tsv"), "utf8")
  .split("\n")
  .filter((line) => line.trim() && !line.startsWith("#"))
  .map((line) => {
    const [retired, successor, relation] = line.split("\t");
    if (currentCodes.has(retired)) throw new Error(`successor table: ${retired} is current`);
    if (!currentCodes.has(successor)) throw new Error(`successor table: ${successor} is not current`);
    if (!["same", "into", "part"].includes(relation)) throw new Error(`successor table: relation ${relation}`);
    return [retired, successor, relation];
  })
  .sort(([a, b], [c, d]) => a.localeCompare(c) || b.localeCompare(d));
// Official 12xxx codes (광주·전남) → the client code the server reads.
const aliases = [...legacy]
  .filter(([current]) => current.startsWith("12"))
  .sort(([a], [b]) => a.localeCompare(b));

// Prefix → canonical region key, as mazimi_core::structural::district_region.
const PREFIX = {
  11: "seoul", 26: "busan", 27: "daegu", 28: "incheon", 29: "gwangju", 30: "daejeon",
  31: "ulsan", 36: "sejong", 41: "gyeonggi", 51: "gangwon", 43: "chungbuk",
  44: "chungnam", 52: "jeonbuk", 46: "jeonnam", 47: "gyeongbuk", 48: "gyeongnam", 50: "jeju",
};
// Order and labels of apps/mobile/constants/regions.ts.
const LABELS = {
  seoul: "서울", busan: "부산", daegu: "대구", incheon: "인천", gwangju: "광주", daejeon: "대전",
  ulsan: "울산", sejong: "세종", gyeonggi: "경기", gangwon: "강원", chungbuk: "충북",
  chungnam: "충남", jeonbuk: "전북", jeonnam: "전남", gyeongbuk: "경북", gyeongnam: "경남", jeju: "제주",
};

const grouped = Object.fromEntries(Object.keys(LABELS).map((key) => [key, []]));
// `${sido}|${name}` → client code, to find the 시 a 구 belongs to.
const byName = new Map();
for (const [current, sido, name] of districts) {
  const code = current.startsWith("12") ? legacy.get(current) : current;
  const region = code && PREFIX[code.slice(0, 2)];
  if (!region) throw new Error(`no client code for ${current} ${name}`);
  // 세종특별자치시 has no 시·군·구 below it; its one row has no name.
  grouped[region].push([code, name || sido]);
  byName.set(`${sido}|${name.trim()}`, code);
}
// A 구 of a 시 is named "수원시 영통구" in the official file; its parent is
// the row named "수원시" in the same sido. Read from the names, never the
// digits (영동군 43740 and 증평군 43745 share four digits).
const parents = [];
for (const [current, sido, name] of districts) {
  const parts = name.trim().split(/\s+/);
  if (parts.length === 1) continue;
  if (parts.length !== 2) throw new Error(`unexpected district name ${current} ${name}`);
  const parent = byName.get(`${sido}|${parts[0]}`);
  if (!parent) throw new Error(`no parent 시 for ${current} ${name}`);
  parents.push([byName.get(`${sido}|${name.trim()}`), parent]);
}
parents.sort(([a], [b]) => a.localeCompare(b));
for (const [region, rows] of Object.entries(grouped)) {
  if (!rows.length) throw new Error(`no districts for ${region}`);
  rows.sort(([a], [b]) => a.localeCompare(b));
}

const body = Object.entries(grouped)
  .map(([region, rows]) => `  ${region}: [\n${rows.map(([c, n]) => `    ["${c}", "${n}"],\n`).join("")}  ],\n`)
  .join("");
const output = `// Generated by scripts/gen-district-codes.mjs from crates/worker/src/district_codes.rs.
// Do not edit by hand; rerun the script after the district table changes.

/** Canonical region key (mazimi_core::canonical_region_code) → short label. */
export const DISTRICT_REGION_LABELS = ${JSON.stringify(LABELS)} as const;

export type DistrictRegion = keyof typeof DISTRICT_REGION_LABELS;

/** [city_code, 시·군·구 name] per region. A 시 with 구 is listed itself and
 * as "수원시 영통구" for each 구. city_code is the code the server reads. */
export const DISTRICTS: Record<DistrictRegion, readonly (readonly [string, string])[]> = {
${body}};
`;

for (const target of ["apps/web/src/lib/districts.generated.ts", "apps/mobile/constants/districts.generated.ts"]) {
  writeFileSync(join(root, target), output);
  console.log(`wrote ${target}`);
}

// The same codes for the server's city_code check, sorted for binary search.
const codes = Object.values(grouped).flat().map(([code]) => code).sort();
const rust = `//! Generated by scripts/gen-district-codes.mjs from crates/worker/src/district_codes.rs.
//! Do not edit by hand; rerun the script after the district table changes.

/// Every city_code a client may send: one per current 시·군·구, in the
/// numbering [\`crate::structural::district_region\`] reads (광주 29xxx,
/// 전남 46xxx, 강원 51xxx, 전북 52xxx). Sorted.
pub const CITY_CODES: &[&str] = &[
${codes.map((code) => `    "${code}",\n`).join("")}];

/// \`(구 code, 시 code)\` for every 구 of a 시 that has them (영통구 41117 →
/// 수원시 41110), read from the official names, never from the digits.
/// Sorted by 구 code.
pub const CITY_PARENTS: &[(&str, &str)] = &[
${parents.map(([child, parent]) => `    ("${child}", "${parent}"),\n`).join("")}];

/// \`(official code, city_code)\` for the official file's 광주·전남 12xxx
/// numbering, which the server reads under the retired 29xxx/46xxx code.
/// Sorted by official code. A retired code (인천 중구 28110, 군위군 47720)
/// stays unresolved here: a stored row may still pair it with its old sido.
/// Ingestion resolves a whole successor ([\`SUCCESSORS\`] \`same\`) when it
/// writes a row, sido and district together.
pub const CODE_ALIASES: &[(&str, &str)] = &[
${aliases.map(([official, client]) => `    ("${official}", "${client}"),\n`).join("")}];

/// \`(retired, successor, relation)\` from the reviewed table
/// scripts/district-successors.tsv (statutes cited there): \`same\` the
/// retired district is the successor whole, \`into\` it became part of the
/// successor, \`part\` part of it became the successor. Sorted.
pub const SUCCESSORS: &[(&str, &str, &str)] = &[
${successors.map(([retired, successor, relation]) => `    ("${retired}", "${successor}", "${relation}"),\n`).join("")}];
`;
writeFileSync(join(root, "crates/core/src/districts.rs"), rust);
// Match the committed layout so `cargo fmt --check` stays green.
execFileSync("rustfmt", ["--edition", "2021", join(root, "crates/core/src/districts.rs")]);
console.log("wrote crates/core/src/districts.rs");
